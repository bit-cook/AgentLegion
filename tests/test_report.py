import tempfile
import unittest
from pathlib import Path

from agent_legion.config import load_config
from agent_legion.environment import Environment
from agent_legion.report import render_report, write_report


class TestReport(unittest.TestCase):
    def setUp(self):
        config = load_config({}).replace(
            INITIAL_AGENTS=5,
            MAX_AGENTS=10,
            GENERATIONS=6,
            SEED=77,
            PROBLEM="sphere",
            LLM_BACKEND="mock",
        )
        self.result = Environment(config).run_simulation()

    def test_report_contains_real_numbers(self):
        text = render_report(self.result)
        summary = self.result.summary()
        self.assertIn(f"{summary['final_best']:.4f}", text)
        self.assertIn(f"{summary['initial_best']:.4f}", text)

    def test_report_structure(self):
        text = render_report(self.result)
        for section in ("# AgentLegion Experiment Report", "## Methodology",
                        "## Results", "## Best Agent", "## Findings", "## Reproduce"):
            self.assertIn(section, text)

    def test_report_marks_itself_as_generated(self):
        text = render_report(self.result)
        self.assertIn("Generated by", text)

    def test_report_reproduces_seed_and_problem(self):
        text = render_report(self.result)
        self.assertIn("sphere", text)
        self.assertIn("--seed 77", text)

    def test_report_uses_provided_findings(self):
        text = render_report(self.result, extra_findings=["custom finding here"])
        self.assertIn("custom finding here", text)

    def test_write_report_creates_file(self):
        with tempfile.TemporaryDirectory() as tmp:
            path = Path(tmp) / "REPORT.md"
            write_report(self.result, str(path))
            content = path.read_text(encoding="utf-8")
            self.assertIn("AgentLegion Experiment Report", content)

    def test_no_placeholder_text(self):
        text = render_report(self.result)
        for placeholder in ("TODO", "TBD", "XXX", "lorem"):
            self.assertNotIn(placeholder, text)


if __name__ == "__main__":
    unittest.main()
