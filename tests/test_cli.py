import csv
import json
import os
import subprocess
import sys
import tempfile
import unittest
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parents[1]


def run_cli(args, env_extra=None):
    env = dict(os.environ)
    env["OPENAI_API_KEY"] = ""  # force the deterministic mock backend
    env.pop("AGENTLEGION_LLM_BACKEND", None)
    if env_extra:
        env.update(env_extra)
    return subprocess.run(
        [sys.executable, "main.py", *args],
        cwd=REPO_ROOT,
        env=env,
        capture_output=True,
        text=True,
        timeout=120,
    )


class TestCliRun(unittest.TestCase):
    def test_version(self):
        result = run_cli(["--version"])
        self.assertEqual(result.returncode, 0, result.stderr)
        self.assertIn("agentlegion 1.0.0", result.stdout)

    def test_bare_invocation_runs_demo(self):
        result = run_cli(["--seed", "5", "--generations", "3", "--population", "10"])
        self.assertEqual(result.returncode, 0, result.stderr)
        self.assertIn("Initializing AgentLegion...", result.stdout)
        self.assertIn("Simulation Complete", result.stdout)

    def test_quiet_outputs_json(self):
        result = run_cli(["--seed", "5", "--generations", "3", "--quiet"])
        self.assertEqual(result.returncode, 0, result.stderr)
        payload = json.loads(result.stdout.strip().splitlines()[-1])
        self.assertEqual(payload["generations"], 3)
        self.assertEqual(payload["seed"], 5)

    def test_explicit_run_subcommand(self):
        result = run_cli(["run", "--seed", "1", "--generations", "2", "--quiet"])
        self.assertEqual(result.returncode, 0, result.stderr)

    def test_problem_choice(self):
        result = run_cli(["run", "--problem", "sphere", "--seed", "1", "--quiet"])
        self.assertEqual(result.returncode, 0, result.stderr)
        payload = json.loads(result.stdout.strip().splitlines()[-1])
        self.assertEqual(payload["problem"], "sphere")

    def test_unknown_problem_fails_with_exit_2(self):
        result = run_cli(["run", "--problem", "banana"])
        self.assertEqual(result.returncode, 2)
        self.assertIn("invalid choice", result.stderr)

    def test_invalid_config_fails_with_exit_2(self):
        result = run_cli(["run", "--initial", "20", "--population", "10"])
        self.assertEqual(result.returncode, 2)
        self.assertIn("configuration error", result.stderr)

    def test_module_invocation(self):
        result = subprocess.run(
            [sys.executable, "-m", "agent_legion.cli", "run", "--seed", "2", "--quiet"],
            cwd=REPO_ROOT,
            capture_output=True,
            text=True,
            timeout=120,
        )
        self.assertEqual(result.returncode, 0, result.stderr)


class TestCliExperiment(unittest.TestCase):
    def test_experiment_writes_csv_and_report(self):
        with tempfile.TemporaryDirectory() as tmp:
            csv_path = os.path.join(tmp, "results.csv")
            report_path = os.path.join(tmp, "REPORT.md")
            result = run_cli(
                [
                    "experiment",
                    "--trials",
                    "2",
                    "--generations",
                    "4",
                    "--population",
                    "10",
                    "--quiet",
                    "--csv",
                    csv_path,
                    "--report",
                    report_path,
                ]
            )
            self.assertEqual(result.returncode, 0, result.stderr)
            with open(csv_path, newline="", encoding="utf-8") as handle:
                rows = list(csv.DictReader(handle))
            self.assertEqual(len(rows), 8)  # 2 trials x 4 generations
            self.assertEqual(
                sorted(rows[0].keys()),
                ["Best_Score", "Generation", "Mean_Score", "Population", "Trial"],
            )
            report = Path(report_path).read_text(encoding="utf-8")
            self.assertIn("Generated by", report)
            self.assertIn("Methodology", report)

    def test_historical_experiment_entry_point(self):
        with tempfile.TemporaryDirectory() as tmp:
            csv_path = os.path.join(tmp, "r.csv")
            report_path = os.path.join(tmp, "R.md")
            result = subprocess.run(
                [
                    sys.executable,
                    "experiment.py",
                    "--trials",
                    "2",
                    "--generations",
                    "3",
                    "--quiet",
                    "--csv",
                    csv_path,
                    "--report",
                    report_path,
                ],
                cwd=REPO_ROOT,
                capture_output=True,
                text=True,
                timeout=120,
            )
            self.assertEqual(result.returncode, 0, result.stderr)
            self.assertTrue(os.path.exists(csv_path))
            self.assertTrue(os.path.exists(report_path))

    def test_historical_config_shim_import(self):
        result = subprocess.run(
            [
                sys.executable,
                "-c",
                "from config import Config, load_config; print(load_config().MAX_AGENTS)",
            ],
            cwd=REPO_ROOT,
            capture_output=True,
            text=True,
            timeout=60,
        )
        self.assertEqual(result.returncode, 0, result.stderr)
        self.assertEqual(result.stdout.strip(), "50")


if __name__ == "__main__":
    unittest.main()
