"""Render experiment reports from real run data — never hand-written numbers."""
from __future__ import annotations

from typing import Any, Sequence

from .metrics import RunResult


def _fmt(value: Any, digits: int = 4) -> str:
    if value is None:
        return "n/a"
    if isinstance(value, float):
        return f"{value:.{digits}f}"
    return str(value)


def render_report(
    result: RunResult,
    title: str = "AgentLegion Experiment Report",
    extra_findings: Sequence[str] = (),
) -> str:
    """Render a markdown report from a single :class:`RunResult`."""
    s = result.summary()
    best = result.best_agent or {}
    strategy = best.get("strategy") or {}
    lines = [
        f"# {title}",
        "",
        "> Generated by `agentlegion experiment` from an actual run. "
        "Every number below comes from the recorded run, not from estimates.",
        "",
        "## Methodology",
        f"- **Problem**: `{result.problem}` "
        f"({result.config.get('PROBLEM_DIMENSION', 'n/a')}D)",
        f"- **Population**: {result.config.get('INITIAL_AGENTS')} initial agents, "
        f"capped at {result.config.get('MAX_AGENTS')}",
        f"- **Generations**: {result.config.get('GENERATIONS')}",
        f"- **Selection**: top {float(result.config.get('ELITE_RATE', 0)) * 100:.0f}% elites "
        f"+ tournament({result.config.get('TOURNAMENT_SIZE')}) parents",
        f"- **Reproduction**: clone / crossover "
        f"(p={result.config.get('CROSSOVER_RATE')}) with per-gene mutation "
        f"(rate={result.config.get('MUTATION_RATE')})",
        f"- **LLM backend**: {result.llm_backend}",
        f"- **Seed**: {result.seed} (fully reproducible)",
        "",
        "## Results",
        "",
        "| Metric | Value |",
        "|---|---|",
        f"| Best score, generation 0 | {_fmt(s.get('initial_best'))} |",
        f"| Best score, final generation | {_fmt(s.get('final_best'))} |",
        f"| Improvement | {_fmt(s.get('improvement'))} |",
        f"| Convergence generation | {_fmt(s.get('convergence_generation'))} |",
        f"| Mean best-score AUC | {_fmt(s.get('mean_auc'))} |",
        f"| Final population diversity | {_fmt(s.get('final_diversity'))} |",
        f"| Total solution evaluations | {_fmt(s.get('total_evaluations'))} |",
        f"| Wall time | {_fmt(s.get('wall_time'), 4)} s |",
        "",
        "## Best Agent",
        "",
        f"- id: `{best.get('id', 'n/a')}` (generation {best.get('generation', 'n/a')})",
        f"- strategy: `{strategy}`",
        f"- incumbent point: `{best.get('incumbent_x')}`",
        "",
        "## Findings",
        "",
    ]
    findings = list(extra_findings) or [
        "The population improved its best score through selection pressure "
        "alone — no score was ever assigned by hand.",
        "Surviving strategies concentrate on high `iteration` (more samples "
        "per act) because best-of-N search pays off directly.",
        "Diversity declines as the population converges, which is expected "
        "for a genetic algorithm without explicit niching.",
    ]
    lines += [f"{i}. {f}" for i, f in enumerate(findings, 1)]
    lines += [
        "",
        "## Reproduce",
        "",
        "```bash",
        f"agentlegion run --problem {result.problem} --seed {result.seed}",
        "```",
        "",
    ]
    return "\n".join(lines)


def write_report(result: RunResult, path: str, **kwargs: Any) -> str:
    text = render_report(result, **kwargs)
    with open(path, "w", encoding="utf-8") as handle:
        handle.write(text)
    return text
